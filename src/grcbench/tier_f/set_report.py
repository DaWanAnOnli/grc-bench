"""The Tier-F first-set report (reports/tier_f_first_set.md), written by `./gb tier-f report`.

Everything in it is read from the task folders, their gates.json, the review records and the
signature audit (compose.audit_items), so it can be regenerated at any time:
  1. coverage: split x family x level
  2. sources: composed chains, GNU Radio examples (with their seed split) and generated chains
  3. split discipline: each reference's signature-v2 cell, the split that cell hashes to, twin groups
  4. gates: solvability, size, variants, start state, mutants
  5. reviews: where the review records are
  6. decisions left to the team
"""

from __future__ import annotations

import datetime as dt
import json
from collections import Counter
from pathlib import Path

from ..common.io import read_json
from ..common.paths import REPO, REPORTS
from . import compose, taskio

FAMILIES = ["build", "modify", "repair", "parameter-tune"]
LEVELS = ["L1", "L2", "L3"]
REVIEWS = REPORTS / "tier_f_reviews"
# Where a set-level decision of fix_plan.md section 7 stands in the items (1-based, as numbered there).
DECISION_STATE = {
    7: "dev-01 and dev-07 check the method with graph checks (a path through a block with memory; the "
       "sources behind stream_a.dat and stream_b.dat reach mux_out.dat); test-05 keeps a documented limit; "
       "'keep the Throttle' is a graph check in dev-07.",
    8: "Settled in the items: dev-10's fault is on the Null Source (type float), and test-17 keeps the "
       "Polyphase Clock Sync fault.",
}


def _gates(task_dir: Path) -> dict | None:
    p = task_dir / "gates.json"
    return read_json(p) if p.exists() else None


def _coverage(tasks: list[dict]) -> list[str]:
    out = []
    for split in ("test", "dev"):
        sub = [t for t in tasks if t["split"] == split]
        c = Counter((t["family"], t["level"]) for t in sub)
        out += [f"**{split}** ({len(sub)} tasks)", "", "| family | " + " | ".join(LEVELS) + " | total |",
                "|---|" + "---|" * (len(LEVELS) + 1)]
        for fam in FAMILIES:
            row = [c[(fam, lev)] for lev in LEVELS]
            out.append(f"| {fam} | " + " | ".join(str(v) if v else "–" for v in row) + f" | {sum(row)} |")
        out.append("")
    return out


def _gate_row(t: dict, g: dict | None) -> str:
    if g is None:
        return f"| {t['id']} | not run | | | | | |"
    gg = g["gates"]
    sol = gg["solvability"]
    st = gg["start_fails"]
    mu = gg["mutation"]
    start = "n/a (build)" if t["family"] == "build" else f"fails at {st.get('first_failed')}"
    return (f"| {t['id']} | {'pass' if g['passed'] else '**FAIL**'} | {sol['passes']}/{sol['runs']} | "
            f"{gg['size']['tokens']} | {gg['variants']['n']} | {start} | "
            f"{mu['valid_mutants']} / {mu['kill_rate']:.2f} |")


def build(today: str | None = None) -> str:
    dirs = taskio.task_dirs()
    tasks = [taskio.load(d) for d in dirs]
    gates = {t["id"]: _gates(d) for t, d in zip(tasks, dirs)}
    audit = compose.audit_items(REPO)
    rows = {r["task"]: r for r in audit["rows"]}
    n_pass = sum(1 for g in gates.values() if g and g["passed"])
    n_test = sum(t["split"] == "test" for t in tasks)
    pending = sum(t["review"]["status"] == "pending-team-review" for t in tasks)
    n_gen = sum(t["source"]["kind"] == "generated_chain" for t in tasks)
    today = today or dt.date.today().isoformat()

    L = [
        "# Tier F first set: status for team review",
        "",
        f"Generated by `./gb tier-f report` on {today} from the task folders, their `gates.json` files, the "
        "review records and the signature audit. Regenerate it after any change to a task.",
        "",
        f"The set has **{len(tasks)} tasks: {len(tasks) - n_test} dev and {n_test} test**. Claude "
        f"(Anthropic) drafted the instructions, reference flowgraphs and oracles of {len(tasks) - n_gen} tasks; "
        f"the other {n_gen} come from the seeded generator `grcbench.tier_f.generate`, which Claude wrote. "
        f"**{n_pass} of {len(tasks)} pass every automatic gate.** {pending} of {len(tasks)} are waiting for the "
        "two-person team review (`docs/checklists/tier_f_task_review.md`). Nothing is used until two team "
        "members approve it. The review sheet is `handoff/review_sheets/tier_f_first_set.csv`; fill in a copy.",
        "",
        "## 1. Coverage",
        "",
        "Families and levels follow the eval plan (§4.3): L1 is a single-rate chain of at most 5 blocks, L2 has "
        "6–15 blocks with rate changes, modulation or filtering, L3 has message ports, tags or more blocks.",
        "",
    ]
    L += _coverage(tasks)

    kinds = Counter(t["source"]["kind"] for t in tasks)
    per_cell = Counter((t["split"], t["level"], t["cluster_id"]) for t in tasks)
    most = {lev: max([n for (_, lv, _), n in per_cell.items() if lv == lev] or [0]) for lev in LEVELS}
    cells = {s: len({c for (sp, _, c) in per_cell if sp == s}) for s in ("test", "dev")}
    L += ["## 2. Sources", "",
          f"- **{kinds.get('composed_chain', 0)} composed tasks**, written from scratch on textbook themes. Their split "
          "is the split their signature-v2 cell hashes to.",
          f"- **{kinds.get('gnuradio_example', 0)} tasks from GNU Radio 3.10.12 example flowgraphs** (GPL-3.0-or-later), "
          "converted to run headless and with their numbers changed (`perturbation` in each task). Each example is "
          "assigned to one split at file level (`splits/flowgraph_seed_split.json`), and a task uses only examples of "
          "its own split.",
          f"- **{kinds.get('generated_chain', 0)} generated tasks** (`./gb tier-f generate`). A seeded generator draws "
          "a chain of stages on a set of tones, computes every expected feature exactly from the tones, and keeps a "
          "task only if its cell hashes to the task's split and the task passes every gate. Each task's `build.py` "
          "rebuilds it from its recorded attempt. An L2 task has a cell of its own. A single-rate chain of at most "
          "5 blocks has few function combinations, and the retune template of L3 reaches few cells, so tasks of one "
          f"split may share a cell: at most {most['L1']} L1 tasks and {most['L3']} L3 tasks per cell. Tasks of one cell "
          "share a `cluster_id`, and the clustered standard errors count the cell once: the test split has "
          f"{cells['test']} cells, the dev split {cells['dev']}.", "",
          "| task | split | example | example's split |", "|---|---|---|---|"]
    for t in tasks:
        if t["source"]["kind"] == "gnuradio_example":
            L.append(f"| {t['id']} | {t['split']} | `{t['source']['ref']}` | {rows[t['id']]['rule_split']} |")
    L.append("")

    conflicts = [r["task"] for r in audit["rows"] if r["conflict"]]
    cross = [g for g in audit["twin_groups"] if len(g["splits"]) > 1]
    hashes = Counter(r["v2_split"] for r in audit["reserved"])
    L += ["## 3. Split discipline", "",
          "Signature v2 describes a flowgraph by the set of functions its blocks perform, so reordering blocks or "
          "adding an inert block (a Throttle) does not change it (`reports/tier_f_signature_v2.md`). A composed task's "
          "split must equal the split its reference cell hashes to. An example task's split comes from its example file, "
          "so its cell may hash to any split; that cell is reserved like every other test and dev cell. A generated "
          "task follows the composed rule.",
          "",
          f"- Tasks whose split disagrees with the rule: **{len(conflicts)}**" + (f" ({', '.join(conflicts)})" if conflicts else "") + ".",
          f"- Groups of tasks that share a reference cell across splits: **{len(cross)}**"
          + ("".join(f"\n  - {', '.join(g['tasks'])}: `{'|'.join(g['v2_signature'])}`" for g in cross)) + ".",
          f"- Reserved cells (reference and variant cells of test and dev tasks, plus the start and golden "
          f"end-state cells of the Tier-A tasks, kept out of training data): "
          f"**{len(audit['reserved'])}** ({hashes.get('test', 0)} hash to test, {hashes.get('dev', 0)} to dev, "
          f"{hashes.get('train', 0)} to train). The training team excludes all of them.",
          "", "| task | split | source | reference cell (v2) | cell hashes to |", "|---|---|---|---|---|"]
    for t in tasks:
        r = rows[t["id"]]
        L.append(f"| {t['id']} | {t['split']} | {'example' if t['source']['kind'] == 'gnuradio_example' else 'composed'} "
                 f"| `{'|'.join(r['v2_signature'])}` | {r['v2_split']} |")
    L.append("")

    L += ["## 4. Gates", "",
          "`./gb tier-f gates all` runs five gates on every task:",
          "- **solvability**: the reference passes V1–V5 in 10 of 10 runs, 8 at a time;",
          "- **size**: the reference fits in 3,000 tokens;",
          "- **variants**: other valid solutions pass V5 (at least two);",
          "- **start state**: a modify, repair or parameter-tune task's start graph fails;",
          "- **mutation**: at least 90 % of the broken versions of the reference fail V5.", "",
          "| task | gates | solvable | tokens | variants | start graph | mutants / kill rate |",
          "|---|---|---|---|---|---|---|"]
    L += [_gate_row(t, gates[t["id"]]) for t in tasks]
    L.append("")

    r1 = len(list((REVIEWS / "round1").glob("gbf-*.json"))) - len(list((REVIEWS / "round1").glob("*.resolution.json")))
    r2 = sorted(p.stem for p in (REVIEWS / "round2").glob("g*.json")) if (REVIEWS / "round2").exists() else []
    L += ["## 5. Reviews", "",
          f"- **Generated tasks ({n_gen}):** checked by the automatic gates only; each waits for the two-person team "
          "review.",
          f"- **First review:** one review per hand-drafted task ({r1} records, `reports/tier_f_reviews/round1/<task>.json`). Each "
          "finding was accepted or rejected with a reason in `<task>.resolution.json`; the set-level plan is "
          "`reports/tier_f_reviews/fix_plan.md`.",
          f"- **Second review:** one reviewer per group of three tasks ({len(r2)} groups, "
          "`reports/tier_f_reviews/round2/<group>.json`). Its findings are resolved in the `round2` entry of the "
          "task's resolution record. Group g2 (gbf-test-03, gbf-dev-02, gbf-dev-05) had a checklist pass instead.",
          "- Each task's `review.notes` (the `known_limits` column of the review sheet) lists the oracle's known "
          "limits and the questions left to the team.", ""]

    fp = read_json(REVIEWS / "fix_plan.json")
    L += ["## 6. Decisions for the team", "", "**For the whole set** (`fix_plan.md` §7):", ""]
    L += [f"{i}. {d}" + (f" *State:* {DECISION_STATE[i]}" if i in DECISION_STATE else "")
          for i, d in enumerate(fp["team_decisions"], 1)]
    L += ["", "**For single tasks:** the tasks whose notes ask for a decision are listed below; the full text is in the "
          "`known_limits` column.", ""]
    for t in tasks:
        notes = t["review"].get("notes", "")
        if "Team decision" in notes or "team decision" in notes or "team should confirm" in notes:
            L.append(f"- {t['id']}")
    L.append("")
    return "\n".join(L)


def write(path: Path | None = None) -> Path:
    path = path or REPORTS / "tier_f_first_set.md"
    path.write_text(build(), encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":
    print(json.dumps({"written": str(write())}))

def _setting_text(cls, params: dict[str, str]) -> str:
    """The setting in GRC's own words: "Type Float->Float (Real Taps), Decimation 4, Taps [0.25]*16"."""
    parts = []
    for prm in cls.parameters_data:
        if prm["id"] not in params:
            continue
        value = params[prm["id"]]
        if prm.get("dtype") == "enum":
            opts = [str(o) for o in prm.get("options") or []]
            labels = [str(x) for x in prm.get("option_labels") or opts]
            value = labels[opts.index(value)] if value in opts else value
        parts.append(f"{prm['label']} {value}")
    return ", ".join(parts)


def _rate_question(grc: Grc, block_id: str, cls, run_check: bool) -> list[dict]:
    if block_id not in RATE_SETTINGS:
        return []
    params, factor = RATE_SETTINGS[block_id]
    ok, errs = grc.valid(block_id, params)
    if not ok:
        raise ValueError(f"{block_id}: rate setting not valid in GRC: {errs}")
    measured = _measure_rate(grc, block_id, params) if run_check else None
    if run_check and (measured is None or abs(measured / factor - 1) > 0.01):
        raise ValueError(f"{block_id}: measured rate factor {measured} differs from {factor}")
    value = RATE_IN * factor
    return [{"kind": "output_rate", "setting": params, "answer": {"value": value, "unit": "S/s"},
             "question": (f"In GNU Radio 3.10, the {cls.label} block ({_code(block_id)}) is set to "
                          f"{_setting_text(cls, params)}, with its other parameters at their defaults. Its input "
                          f"runs at {RATE_IN} samples per second. At what sample rate does it produce output "
                          "samples?"),
             "evidence": (f"rate factor {factor:g}; confirmed by running the flowgraph: output/input item ratio "
                          f"{measured:.5f}" if measured is not None else f"rate factor {factor:g} (run not checked)")}]


def _measure_rate(grc: Grc, block_id: str, params: dict[str, str]) -> float | None:
    """Run a finite Vector Source -> block, with the block's input and output observed, and return
    output items / input items."""
    import numpy as np

    from grcbench.tier_f import grcfile, ladder
    _, blk = grc.place(block_id, params)
    din = grc.stream(blk.sinks)[0].dtype
    dout = grc.stream(blk.sources)[0].dtype
    vec = f"[0.1*((i*7)%13) for i in range({RATE_ITEMS})]"
    data = {"options": {"parameters": {"id": "rateprobe", "generate_options": "no_gui", "output_language": "python"}},
            "blocks": [{"name": "samp_rate", "id": "variable", "parameters": {"value": str(RATE_IN)}},
                       {"name": "src", "id": "blocks_vector_source_x",
                        "parameters": {"type": din, "vector": vec, "repeat": "False"}},
                       {"name": "dut", "id": block_id, "parameters": dict(params)},
                       {"name": "tap_in", "id": "blocks_file_sink", "parameters": {"type": din, "file": "in.dat"}},
                       {"name": "tap_out", "id": "blocks_file_sink", "parameters": {"type": dout, "file": "out.dat"}}],
            "connections": [["src", "0", "dut", "0"], ["src", "0", "tap_in", "0"], ["dut", "0", "tap_out", "0"]],
            "metadata": {"file_format": 1}}
    task = {"observation": {"points": [
        {"name": "in", "sink": {"block_id": "blocks_file_sink", "params": {"file": "in.dat", "type": din}}},
        {"name": "out", "sink": {"block_id": "blocks_file_sink", "params": {"file": "out.dat", "type": dout}}}],
        "run": {"n_items": 10 * RATE_ITEMS, "min_items": 1, "timeout_s": 60}},
        "oracle": {"checks": [{"point": "in", "feature": "max_abs", "max": 1e9}]}}
    import shutil
    root = WORK / "blockq" / block_id
    shutil.rmtree(root, ignore_errors=True)
    root.mkdir(parents=True)
    res = ladder.check(grcfile.dump(data), task, keep=True, run_root=root, timeout=180)
    run_dirs = [d for d in root.iterdir() if d.is_dir()]
    obs = run_dirs[0] / "obs" if len(run_dirs) == 1 else None
    if res.get("highest_passed") not in ("V5", "V6") or obs is None or not (obs / "in.npy").exists():
        return None
    n_in, n_out = len(np.load(obs / "in.npy")), len(np.load(obs / "out.npy"))
    return n_out / n_in if n_in else None


def _count_questions(grc: Grc, block_id: str, cls) -> list[dict]:
    out = []
    for a in cls.asserts or []:
        m = re.match(r"^\s*\$?\{?\s*num_inputs\s*(>=|>)\s*(\d+)\s*\}?\s*$", a.strip())
        if m:
            low = int(m.group(2)) + (1 if m.group(1) == ">" else 0)
            if low >= 2:
                ok_lo, _ = grc.valid(block_id, {"num_inputs": str(low)})
                ok_below, _ = grc.valid(block_id, {"num_inputs": str(low - 1)})
                if ok_lo and not ok_below:
                    out.append({"kind": "port_count", "setting": {"num_inputs": str(low)},
                                "answer": {"value": low, "unit": ""},
                                "question": (f"In GNU Radio Companion 3.10, what is the smallest number of inputs "
                                             f"the {cls.label} block ({_code(block_id)}) accepts?"),
                                "evidence": f"assert '{a.strip()}': num_inputs={low} validates, {low - 1} does not"})
                    return out
    _, blk = grc.place(block_id)
    outs = grc.stream(blk.sources)
    if len(outs) >= 2 and not any("${" in str(x.get("multiplicity", "")) for x in cls.outputs_data or []):
        out.append({"kind": "port_count", "setting": {}, "answer": {"value": len(outs), "unit": ""},
                    "question": (f"In GNU Radio 3.10, how many output stream ports does the {cls.label} block "
                                 f"({_code(block_id)}) have?"),
                    "evidence": f"GRC Platform API: {block_id} has {len(outs)} output stream ports"})
    return out


# --------------------------------------------------------------------------- references and checks
def reference(q: dict) -> Any:
    a = q["answer"]
    if q["kind"] in ("output_type", "input_type"):
        return {"exact": a, "aliases": TYPE_ALIASES[a], "universe": list(TYPES)}
    if q["kind"] == "enum_choices":
        return {"set": a, "universe": a, "aliases": q.get("aliases", {})}
    if q["kind"] == "message_ports":
        return {"set": a} if isinstance(a, list) else {"exact": a}
    return dict(a)


def _answer_text(q: dict) -> tuple[str, str]:
    """A correct and a wrong answer, to check that the rule cascade scores the reference."""
    a = q["answer"]
    if q["kind"] in ("output_type", "input_type"):
        wrong = next(t for t in TYPES if t != a)
        return f"Final answer: {a}", f"Final answer: {wrong}"
    if q["kind"] == "enum_choices":
        return "Final answer: " + ", ".join(a), "Final answer: " + ", ".join(a[:-1])
    if q["kind"] == "message_ports":
        if isinstance(a, list):
            return "Final answer: " + ", ".join(a), "Final answer: " + ", ".join(a[:-1])
        return f"Final answer: {a}", "Final answer: msg_wrong_port"
    unit = " samples per second" if a["unit"] else ""
    return f"Final answer: {a['value']:g}{unit}", f"Final answer: {a['value'] * 2:g}{unit}"


def _rules_check(q: dict) -> str | None:
    from grcbench.tier_k import rules
    ref = reference(q)
    right, wrong = _answer_text(q)
    r1, r0 = rules.score(right, ref), rules.score(wrong, ref)
    if r1["method"] == "judge" or r1["credit"] != 1.0:
        return f"reference answer scores {r1['method']} {r1['credit']} ({r1['details'].get('reason')})"
    if r0["method"] != "judge" and r0["credit"] >= 1.0:
        return f"wrong answer scores {r0['credit']}"
    return None


# --------------------------------------------------------------------------- build
def build(run_check: bool = True) -> dict[str, Any]:
    from grcbench.tier_k import catalog as cat
    part = {b["id"]: b for b in json.loads((SPLITS / "block_partition.json").read_text(encoding="utf-8"))["blocks"]}
    grc = Grc()
    trees = cat.tree_modules()
    bank = _bank()
    questions, dropped, failed = [], [], []
    for block_id in sorted(k for k, b in part.items() if b.get("split") == "test"):
        cls = grc.platform.blocks[block_id]
        rec = cat.block_record(cls, trees)
        made = (_type_questions(grc, block_id, rec, cls) + _enum_question(block_id, rec, cls)
                + _message_question(grc, block_id, cls) + _rate_question(grc, block_id, cls, run_check)
                + _count_questions(grc, block_id, cls))
        for q in made:
            hit = _in_bank(bank, cls.label, block_id, q["kind"])
            if hit:
                dropped.append({"block": block_id, "kind": q["kind"], "bank_question": hit})
                continue
            problem = _rules_check(q)
            if problem:
                failed.append({"block": block_id, "kind": q["kind"], "problem": problem})
                continue
            q.update(block=block_id, label=cls.label, family=part[block_id]["family"],
                     yaml_file=rec["yaml_file"], yaml_sha256=rec["yaml_sha256"])
            questions.append(q)
    candidates = Counter(q["kind"] for q in questions)
    return {"questions": select(questions), "candidates": dict(candidates), "dropped": dropped, "failed": failed,
            "run_check": run_check}


def select(questions: list[dict]) -> list[dict]:
    """TARGET questions: every question of the rarer kinds, then type questions (at most one per block,
    output or input by hash) ranked by sha256(SEED + question id) until TARGET is reached."""
    rest = [q for q in questions if q["kind"] not in TYPE_KINDS]
    per_block: dict[str, list[dict]] = {}
    for q in questions:
        if q["kind"] in TYPE_KINDS:
            per_block.setdefault(q["block"], []).append(q)
    one = [_pick(b, sorted(qs, key=lambda q: q["kind"]), "type-kind") for b, qs in sorted(per_block.items())]
    one.sort(key=lambda q: hashlib.sha256(f"{SEED}\0{_qid(q['block'], q['kind'])}".encode()).hexdigest())
    chosen = rest + one[:max(TARGET - len(rest), 0)]
    return sorted(chosen, key=lambda q: (q["block"], q["kind"]))



"""GNU Radio block questions for Tier K (`./gb blockq`; build plan WS3b; eval plan §4.2, Table 1).

Eval plan §4.2: about 100 GNU Radio questions "generated by a script from the block catalog that
ships with GNU Radio 3.10"; training questions of this kind come from other blocks, so every question
is about a block whose `split` is `test` in splits/block_partition.json. Each question asks about one
property of one block setting, and its answer is read from the block's YAML through GRC's own
Platform API (the block is placed in a flowgraph, set as the question says, rewritten and
validated), never typed in by hand. Kinds:

  output_type    the item type of the block's output stream for one setting of its type parameter
                 (one question per block with a type parameter and a stream output)
  input_type     the item type of the input stream, for blocks whose type options give different
                 input and output types (the type -> I/O mapping, `option_attributes`)
  enum_choices   every choice of a non-type enum parameter with 3-8 choices (scored as a set; yes/no
                 style and colour lists are left out)
  message_ports  the names of the block's message input or output ports (a set, or one name)
  output_rate    the output sample rate for a 96 kS/s input with one decimation / interpolation
                 setting, confirmed by RUNNING the flowgraph (a finite Vector Source, item counts at
                 the block's input and output through the Tier-F ladder)
  port_count     the smallest number of inputs a block with a num_inputs assert accepts, and the
                 number of output ports of blocks with several fixed outputs

Rules: at most one question per (block, kind); a block's family is its cluster_id; choices made among
options use sha256(SEED + block id), so the output is deterministic. A question is dropped when a bank
question (the 1,853 frozen questions) names the same block and the same property (dedup). Every
question passes three checks before it is written: GRC confirms the answer; the rule cascade gives
the reference answer full credit and a wrong answer less (rules.score); the record passes the Tier-K
schema.

Scoring: the rule cascade (exact names, sets of choices, numbers). These questions have no judge
rubric (rubric guide, "Block-catalog questions"): an answer the rules cannot decide is scored by a
team member. Claude wrote the question templates (wording reviewed by the team, Table 7); the facts
come from the YAML.

Outputs (`--out` root, default the repository):
  items/tier_k/test/block_questions.jsonl     the question records (no answers)
  items/tier_k/test/block_answers.jsonl       the answer key (reference for rules.score, evidence)
  handoff/review_sheets/tier_k_block_questions.csv   wording review sheet (two reviewers)
  reports/tier_k_block_questions.md           counts per kind, drops, checks
"""


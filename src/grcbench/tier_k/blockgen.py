# --------------------------------------------------------------------------- helpers
def _pick(block_id: str, options: list, salt: str = "") -> Any:
    h = int(hashlib.sha256(f"{SEED}\0{block_id}\0{salt}".encode()).hexdigest(), 16)
    return options[h % len(options)]


def _qid(block_id: str, kind: str) -> str:
    return "bq_" + hashlib.sha256(f"{SEED}\0{block_id}\0{kind}".encode()).hexdigest()[:16]


def _code(s: str) -> str:
    return f"`{s}`"


def _bank() -> list[str]:
    out = []
    for name in ("eval_questions.jsonl", "train_questions.jsonl"):
        for line in (FROZEN / name).read_text(encoding="utf-8").splitlines():
            if line.strip():
                out.append(json.loads(line)["question"].lower())
    return out


def _in_bank(bank: list[str], label: str, block_id: str, kind: str) -> str | None:
    names = [n.lower() for n in (label, block_id) if n and (n == block_id or len(n) >= MIN_LABEL_CHARS)]
    pat = [re.compile(r"\b" + re.escape(n) + r"\b") for n in names]
    for q in bank:
        if any(p.search(q) for p in pat) and any(w in q for w in KIND_WORDS[kind]):
            return q[:160]
    return None


class Grc:
    """GRC's Platform API: place one block in a fresh flowgraph, set parameters, rewrite, read ports."""

    def __init__(self):
        from grcbench.tier_k import catalog
        self.platform = catalog.load_platform()

    def place(self, block_id: str, params: dict[str, str] | None = None):
        fg = self.platform.make_flow_graph()
        fg.import_data({"options": {"parameters": {"id": "blockq", "generate_options": "no_gui"}, "states": {}},
                        "blocks": [{"name": "samp_rate", "id": "variable", "parameters": {"value": "32000"},
                                    "states": {}},
                                   {"name": "b0", "id": block_id, "parameters": dict(params or {}), "states": {}}],
                        "connections": [], "metadata": {"file_format": 1}})
        fg.rewrite()
        blk = next(b for b in fg.blocks if b.name == "b0")
        return fg, blk

    @staticmethod
    def stream(ports) -> list:
        return [p for p in ports if p.domain != "message"]

    @staticmethod
    def message(ports) -> list:
        return [p for p in ports if p.domain == "message"]

    def valid(self, block_id: str, params: dict[str, str]) -> tuple[bool, list[str]]:
        fg, blk = self.place(block_id, params)
        fg.validate()
        errs = [e for e in blk.get_error_messages() if "not connected" not in e.lower()]
        return not errs, errs


# --------------------------------------------------------------------------- question kinds
def _param(cls, pid: str) -> dict:
    return next(p for p in cls.parameters_data if p["id"] == pid)


TYPE_WORDS = {"complex": {"complex"}, "float": {"float", "real"}, "int": {"int", "integer"},
              "short": {"short"}, "byte": {"byte", "bytes", "char", "uchar", "bit", "bits"}}


def _gives_away(dtype: str, *labels: str) -> bool:
    """The block or option label already names the type ("Float To Short", IO Type "Short"): trivia."""
    words = {w for lab in labels for w in re.split(r"[^a-z]+", lab.lower()) if w}
    return bool(TYPE_WORDS[dtype] & words)


def _type_questions(grc: Grc, block_id: str, rec: dict, cls) -> list[dict]:
    """One output_type and one input_type question per block, about a port whose type the block label and
    the option label do not name (the type -> I/O mapping a GNU Radio user has to know)."""
    pid = rec["type_params"][0] if rec["type_params"] else None
    p = _param(cls, pid) if pid else None
    settings = ([(str(o), str(lab)) for o, lab in zip(p.get("options") or [], p.get("option_labels") or p.get("options") or [])]
                if p else [(None, "")])
    rows = []
    for opt, lab in settings:
        _, blk = grc.place(block_id, {pid: opt} if pid else None)
        ins = [x.dtype for x in grc.stream(blk.sinks)]
        outs = [x.dtype for x in grc.stream(blk.sources)]
        rows.append((opt, lab, ins[0] if ins else None, outs[0] if outs else None))
    out = []
    for kind, idx, verb in (("output_type", 3, "does its output stream carry"), ("input_type", 2, "does its input stream take")):
        cands = [r for r in rows if r[idx] in TYPES and not _gives_away(r[idx], cls.label, r[1])]
        if not cands:
            continue
        opt, lab, din, dout = _pick(block_id, cands, kind)
        dt = dout if kind == "output_type" else din
        setting = f" with its {p['label']} parameter set to {lab}" if pid else ""
        port = "output" if kind == "output_type" else "input"
        out.append({"kind": kind, "setting": {pid: opt} if pid else {}, "answer": dt,
                    "question": (f"In GNU Radio Companion 3.10, take the {cls.label} block ({_code(block_id)}){setting}. "
                                 f"What item type {verb}?"),
                    "evidence": f"GRC Platform API: {block_id}" + (f" with {pid}={opt}" if pid else "")
                                + f": {port} port 0 dtype {dt}"})
    return out


def _enum_question(block_id: str, rec: dict, cls) -> list[dict]:
    cands = []
    for p in cls.parameters_data:
        if p.get("dtype") != "enum" or p["id"] in rec["type_params"] or COLOURISH.search(p.get("label", "")):
            continue
        labels = [str(x) for x in (p.get("option_labels") or p.get("options") or [])]
        if not 3 <= len(labels) <= 8 or {x.lower() for x in labels} <= BOOLISH:
            continue
        if not all(SAFE_LABEL.match(x) for x in labels) or len({x.lower() for x in labels}) != len(labels):
            continue
        if p.get("hide") == "all":                      # never shown in GRC
            continue
        cands.append((p, labels))
    if not cands:
        return []
    p, labels = _pick(block_id, cands, "enum")
    values = [str(x) for x in p.get("options") or []]
    aliases = {lab: [v] for lab, v in zip(labels, values) if v.lower() != lab.lower() and SAFE_LABEL.match(v)}
    return [{"kind": "enum_choices", "setting": {}, "answer": labels, "aliases": aliases,
             "question": (f"In GNU Radio Companion 3.10, which choices does the {p['label']} parameter of the "
                          f"{cls.label} block ({_code(block_id)}) offer? Name all of them."),
             "evidence": f"block YAML: parameter {p['id']} option_labels {labels} (options {values})"}]


def _message_question(grc: Grc, block_id: str, cls) -> list[dict]:
    _, blk = grc.place(block_id)
    sides = []
    for side, ports in (("input", blk.sinks), ("output", blk.sources)):
        names = sorted({str(x.key) for x in grc.message(ports) if not getattr(x, "hidden", False)})
        if names:
            sides.append((side, names))
    if not sides:
        return []
    side, names = _pick(block_id, sides, "msg")
    many = len(names) > 1
    q = (f"In GNU Radio 3.10, what {'are the names of the' if many else 'is the name of the'} message "
         f"{side} port{'s' if many else ''} of the {cls.label} block ({_code(block_id)})?")
    return [{"kind": "message_ports", "setting": {}, "answer": names if many else names[0], "question": q,
             "evidence": f"GRC Platform API: {block_id} message {side} ports {names}"}]


